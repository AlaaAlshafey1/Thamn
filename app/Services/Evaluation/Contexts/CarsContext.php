- CarSwitch (carswitch.com/sa) للمقارنة بالضمان.

قواعد استخدام المراجع:
1. لا تعتمد على سعر الشراء الذي يذكره صاحب السيارة — قد يكون مبالغاً فيه أو كاذباً.
2. ابحث بنفس المعطيات: الماركة + الموديل + السنة + الكيلومترات ± 20,000 كم.
3. خذ متوسط الـ 50% الوسطى من الأسعار (تجاهل الأعلى 25% والأدنى 25%).
4. أسعار حراج عادةً أقل 5-10% من السعر الحقيقي بسبب التفاوض — عوّض عن ذلك.';
    }

    public function getPricingTips(): string
    {
        return '━━ قواعد التسعير الخاصة بالسيارات ━━

الخطوة 1 — تجاهل سعر الشراء:
- سعر الشراء الذي يذكره العميل قد يكون مبالغاً فيه أو غير حقيقي.
- ابنِ تقييمك فقط على: المعطيات الفعلية للسيارة + مقارنة السوق الحالي.
- السعر العادل هو ما تُباع به سيارات مشابهة فعلاً في السوق السعودي اليوم.

الخطوة 2 — تقييم المسافة المقطوعة بذكاء:
- المعدل الطبيعي: 15,000 - 25,000 كم/سنة.
- المسافة العالية على الطرق السريعة (Highway) أقل ضرراً بكثير من المسافة داخل المدينة.
- إذا كانت السيارة في المنطقة الشرقية أو تستخدم للسفر بين المدن → احتمل أن المسافة على طرق سريعة (أرحم على المحرك).
- خصم المسافة العالية يكون تدريجياً وليس خطياً: فرق 50,000 كم لا يعني خصم 50% من السعر.
- قارن بسيارات مشابهة بنفس الكيلومترات في السوق — دع السوق يحدد أثر الكيلومترات.

الخطوة 3 — العوامل التي ترفع السعر:
- الضمان ساري من الوكالة: +5% إلى +10%.
- صيانة منتظمة موثّقة: +3% إلى +5%.
- بدون حوادث مسجلة: +3% إلى +5%.
- إضافات أصلية (طبقة حماية، تظليل عازل، كماليات): +2% إلى +4%.
- حالة ظاهرية ممتازة موثقة بالصورة: +3% إلى +7%.

الخطوة 4 — العوامل التي تخفض السعر:
- المسافة أعلى من المعدل: خصم تدريجي حسب الزيادة ومقارنة السوق.
- حوادث موثقة: -10% إلى -20% حسب الحجم.
- صيانة غير منتظمة: -5% إلى -10%.
- أعطال أو عيوب ظاهرة: -5% إلى -15%.

الخطوة 5 — الحد الأدنى المنطقي:
- لا ينزل السعر عن 35% من سعر الوكالة الجديد للسيارة نفسها، مهما كانت الكيلومترات، ما لم تكن في حالة رديئة جداً موثقة.
- السيارة بضمان سارٍ لا ينبغي أن تقل عن 50% من سعر الوكالة.

- ارجع لأسعار نفس الموديل والسنة والشكل (فيس ليفت / قبل فيس ليفت) في السوق السعودي الحالي.
- السيارات المستوردة الأمريكية (سلفج/كلين) لها أسعار مختلفة جداً عن الوكالة — حددها إن وجدت.';
    }

