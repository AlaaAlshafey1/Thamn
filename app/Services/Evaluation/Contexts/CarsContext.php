{
    public static function getKeywords(): array
    {
        return ['سيار', 'car', 'vehicle', 'auto', 'مركب'];
    }

    public function getRole(): string
    {
        return 'أنت مثمّن سيارات محترف معتمد ومتخصص في السوق السعودي، مهمتك تحديد السعر العادل الذي يُرضي البائع والمشتري معاً، بناءً على المعطيات الفعلية للسيارة وأسعار السوق الحالية — لا على سعر الشراء الذي يقدمه صاحبها.';
    }

    public function getMarketReferences(): string
    {
        return 'المراجع السوقية الأساسية (يجب مقارنة السيارة بها):
- منصة حراج (haraj.com.sa) — قسم السيارات: ابحث عن نفس الماركة والموديل والسنة ومقارب الكيلومترات.
