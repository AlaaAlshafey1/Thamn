use App\Services\Evaluation\Contracts\CategoryEvaluationContext;

class CarsContext implements CategoryEvaluationContext
{
    public static function getKeywords(): array
    {
        return ['سيار', 'car', 'vehicle', 'auto', 'مركب'];
    }

    public function getRole(): string
    {
        return 'أنت مثمّن سيارات محترف معتمد ومتخصص في السوق السعودي، مهمتك تحديد السعر العادل الذي يُرضي البائع والمشتري معاً، بناءً على المعطيات الفعلية للسيارة وأسعار السوق الحالية — لا على سعر الشراء الذي يقدمه صاحبها.';
    }

    public function getMarketReferences(): string
    {
        return 'المراجع السوقية الأساسية (يجب مقارنة السيارة بها):
- منصة حراج (haraj.com.sa) — قسم السيارات: ابحث عن نفس الماركة والموديل والسنة ومقارب الكيلومترات.
- تطبيق موجز (مرجع ثانوي لتأكيد النطاق).
- تطبيق نجم (مرجع ثانوي).
- SyarahCars (syarah.com) لأسعار المستعملة المعتمدة.
- CarSwitch (carswitch.com/sa) للمقارنة بالضمان.

قواعد استخدام المراجع:
1. لا تعتمد على سعر الشراء الذي يذكره صاحب السيارة — قد يكون مبالغاً فيه أو كاذباً.
2. ابحث بنفس المعطيات: الماركة + الموديل + السنة + الكيلومترات ± 20,000 كم.
3. خذ متوسط الـ 50% الوسطى من الأسعار (تجاهل الأعلى 25% والأدنى 25%).
4. أسعار حراج عادةً أقل 5-10% من السعر الحقيقي بسبب التفاوض — عوّض عن ذلك.';
    }

    public function getPricingTips(): string
    {
        return '━━ منهجية التسعير الاحترافية للسيارات ━━

المبدأ الأساسي: ابدأ من سعر الشراء وطبّق معدلات الاستهلاك — هذا ما يفعله أي مثمّن خبير.

الخطوة 1 — استخرج سعر الشراء:
- سعر الشراء المذكور هو نقطة البداية الرياضية للحساب.
- إذا بدا مبالغاً فيه، قلّل الثقة به بنسبة 10-15% فقط — لا تتجاهله كلياً.

الخطوة 2 — طبّق معدل الاستهلاك حسب عمر السيارة:
- السنة الأولى: -15% من سعر الشراء
- السنة الثانية: -10% إضافية
- السنة الثالثة: -8% إضافية
- كل سنة بعد الثالثة: -6% إضافية
مثال: سيارة عمرها 3 سنوات = 131,000 × (1 - 0.15 - 0.10 - 0.08) = 131,000 × 0.67 = 87,770 قبل تعديل الكيلومترات

الخطوة 3 — تعديل الكيلومترات (عامل ثانوي وليس رئيسي):
- المعدل الطبيعي: 20,000 كم/سنة × عمر السيارة
- لكل 10,000 كم فوق المعدل: اخصم 1.5% من السعر بعد الاستهلاك
- الحد الأقصى لخصم الكيلومترات: -20% مهما ارتفعت
- المسافة على الطرق السريعة (مثل المنطقة الشرقية) أقل ضرراً — خفّف الخصم بـ 30%

الخطوة 4 — العوامل التي ترفع السعر (أضفها على النتيجة):
- ضمان ساري من الوكالة: +8% إلى +12%
- صيانة منتظمة موثّقة: +3% إلى +5%
- بدون حوادث: +3% إلى +5%
- حالة ظاهرية ممتازة بالصورة: +4% إلى +7%
- إضافات (حماية، تظليل، كماليات): +2% إلى +4%
- مستخدم واحد فقط: +2%

الخطوة 5 — العوامل التي تخفض السعر:
- حوادث موثقة: -10% إلى -20% حسب الحجم
- صيانة غير منتظمة: -5% إلى -8%
- عيوب ظاهرة (خدوش، دهان): -3% إلى -10%

الخطوة 6 — تحقق نهائي (إلزامي):
- النتيجة النهائية يجب أن تعكس ما تُباع به سيارات مشابهة فعلاً في حراج وموجز ونجم وسيارة.
- سيارة بضمان ساري وحالة ممتازة: لا تنزل عن 55% من سعر الشراء مهما كانت الكيلومترات.
- سيارة بدون ضمان وحالة جيدة: لا تنزل عن 40% من سعر الشراء.
- لا تطبّق خصومات متكررة على نفس العامل.

- السيارات المستوردة الأمريكية (سلفج/كلين) لها أسعار مختلفة — حددها إن وجدت.';
    }

    public function getNoImageDataTips(): string
    {
        return 'احسب السعر بناءً على: السنة، الماركة، الموديل، الفئة، المسافة المقطوعة، نوع الجير. افترض حالة متوسطة إلى جيدة. لا تعتمد على سعر الشراء المذكور.';
    }

    public function getImageAnalysisTips(): string
    {
        return '- قيّم حالة البودي الخارجي (خدوش، رشات دهان، صدمات، أعمال صيانة سابقة).
- لاحظ حالة الإطارات والجنوط (بالي/جديدة، خدوش).
- افحص حالة المقصورة الداخلية (المقاعد، الطبلون، عداد المسافة الفعلي في الصورة).
- تحقق من وجود تعديلات أو إضافات (تظليل، طبقة حماية، شاشات).
- الصورة الواضحة الممتازة ترفع الثقة في التقييم — عبّر عن ذلك في confidence.
- إذا كانت الصورة تُظهر حالة ممتازة لا تتناسب مع كيلومترات عالية، خذ الصورة كدليل أقوى من الأرقام.';
    }
}
